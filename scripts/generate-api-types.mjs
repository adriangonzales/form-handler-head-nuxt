// Generates shared/types/api.d.ts from the API's OpenAPI spec. The spec URL comes from
// API_DOCS_URL, or is derived from NUXT_API_BASE (`…/api` → `…/docs/api.json`). Run through
// `pnpm api:types`, which loads `.env`.
import { writeFile } from 'node:fs/promises'
import openapiTS, { astToString } from 'openapi-typescript'

const apiBase = process.env.NUXT_API_BASE
const docsUrl =
  process.env.API_DOCS_URL ??
  (apiBase ? `${apiBase.replace(/\/+$/, '').replace(/\/api$/, '')}/docs/api.json` : undefined)

if (!docsUrl) {
  console.error('Set NUXT_API_BASE (or API_DOCS_URL) in .env to generate the API types.')
  process.exit(1)
}

const output = new URL('../shared/types/api.d.ts', import.meta.url)
const ast = await openapiTS(new URL(docsUrl))

const banner = `/**\n * Generated by scripts/generate-api-types.mjs from ${docsUrl}. Do not edit by hand.\n */\n\n`

await writeFile(output, banner + astToString(ast))
console.log(`Generated shared/types/api.d.ts from ${docsUrl}`)
